#ifndef TWO_PHASE_MERGE_SORT_H
#define TWO_PHASE_MERGE_SORT_H

#include <string>

// Двухфазная сортировка простым слиянием (Two-Phase Straight Merge Sort)
//
// Внешняя сортировка: данные хранятся не в оперативной памяти, а в файле,
// и обрабатываются последовательно, с использованием вспомогательных
// временных файлов. В памяти одновременно находится только несколько
// элементов.
//
// Формат файла: текстовый, значения разделены пробелами или переводами строк
// (чтение и запись выполняются операторами >> и <<).

// Сортирует по возрастанию значения типа T, записанные в файле fileName.
// Результат записывается в тот же файл.
// Во время работы создаются вспомогательные файлы
// fileName + ".b.tmp" и fileName + ".c.tmp",
// после завершения сортировки они удаляются.
// Если файл не удалось открыть, выбрасывается исключение std::runtime_error.
// Тип T указывается явно, например: twoPhaseMergeSortFile<int>("data.txt");
template <typename T>
void twoPhaseMergeSortFile(const std::string& fileName);

// Сортирует по возрастанию массив array из size элементов.
// Массив записывается во временный файл, файл сортируется внешней
// сортировкой, затем результат считывается обратно в массив,
// а временный файл удаляется.
template <typename T>
void twoPhaseMergeSort(T* array, int size);

#endif // TWO_PHASE_MERGE_SORT_H
